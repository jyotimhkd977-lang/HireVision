/* ============================================================
   RESULT PAGE
   ============================================================ */
function renderResultPage() {
  if (!HV.currentUser) { Router.navigate('auth'); return; }
  if (!HV.lastResult)  { Router.navigate('predict'); return; }

  const r  = HV.lastResult;
  const fd = r.formData || {};
  const placed      = r.placed;
  const confidence  = Math.round(r.probability_placed * 100);
  const outcomeWord = placed ? 'Placed' : 'Not Placed';
  const stampClass  = placed ? 'placed' : 'not-placed';
  const stampText   = placed ? 'Likely Placed' : 'Likely Not Placed';

  const name      = r.candidateName || HV.currentUser.name;
  const branch    = fd.Branch || HV.currentUser.branch || '—';
  const age       = fd.Age || '—';
  const timestamp = r.timestamp ? new Date(r.timestamp).toLocaleString('en-IN', { dateStyle:'medium', timeStyle:'short' }) : 'N/A';

  const breakdowns = computeBreakdowns(fd);
  const remarks = generateRemarks(fd, placed);

  const main = document.getElementById('app-main');
  main.innerHTML = `
    <div class="result-page">
      <div class="container">
        <div class="result-page-header">
          <p class="eyebrow">Evaluation Output</p>
          <h2>Placement Evaluation Result</h2>
          <p style="color:var(--color-navy-mid);font-size:var(--text-sm);">
            Report generated by HireVision AI Model v1.0 · ${r.offline ? 'Local heuristic estimate' : 'API prediction'}
          </p>
        </div>

        <div class="result-report" role="main" aria-label="Evaluation report">

          <!-- Header -->
          <div class="result-report-header">
            <div class="hdr-left">
              <h3>Placement Evaluation Report</h3>
              <p class="sub">HireVision AI · GIET University, Gunupur · ${timestamp}</p>
            </div>
            <span class="result-stamp ${stampClass}" role="status" aria-live="polite">
              ${stampText}
            </span>
          </div>

          <!-- Body -->
          <div class="result-body">

            <!-- Outcome row -->
            <div class="result-outcome-row">
              <div class="result-meta">
                <div class="result-meta-item">
                  <span class="key">Candidate</span>
                  <span class="val">${name}</span>
                </div>
                <div class="result-meta-item">
                  <span class="key">Branch</span>
                  <span class="val">${branch}</span>
                </div>
                <div class="result-meta-item">
                  <span class="key">Age</span>
                  <span class="val">${age}</span>
                </div>
                <div class="result-meta-item">
                  <span class="key">Evaluated</span>
                  <span class="val">${timestamp}</span>
                </div>
              </div>
              <div class="result-big-outcome">
                <span class="outcome-word ${stampClass}" aria-label="Predicted outcome: ${outcomeWord}">
                  ${outcomeWord}
                </span>
                <span class="confidence-pct">
                  ${confidence}% Model Confidence
                </span>
                <div style="margin-top:var(--space-3);">
                  <div class="progress-bar-wrap" style="width:180px;" aria-label="Confidence bar">
                    <div class="progress-bar-fill ${placed ? 'green' : 'red'}"
                         style="width:${confidence}%;"
                         role="progressbar"
                         aria-valuenow="${confidence}"
                         aria-valuemin="0"
                         aria-valuemax="100">
                    </div>
                  </div>
                </div>
              </div>
            </div>

            <!-- Breakdown bars -->
            <div class="breakdown-section">
              <h4>Score Breakdown</h4>
              ${Object.entries(breakdowns).map(([key, val]) => `
                <div class="breakdown-row">
                  <div class="breakdown-header">
                    <span class="breakdown-name">${key}</span>
                    <span class="breakdown-pct">${val}%</span>
                  </div>
                  <div class="progress-bar-wrap" aria-label="${key} score ${val}%">
                    <div class="progress-bar-fill"
                         data-width="${val}"
                         style="width:0%;"
                         role="progressbar"
                         aria-valuenow="${val}"
                         aria-valuemin="0"
                         aria-valuemax="100">
                    </div>
                  </div>
                </div>
              `).join('')}
            </div>

            <!-- Remarks -->
            <div class="remarks-section" aria-label="Improvement suggestions">
              <p class="remarks-title">📋 Remarks &amp; Suggestions</p>
              ${remarks.length ? remarks.map((r, i) => `
                <div class="remark-item">
                  <span class="remark-bullet" aria-hidden="true">${i+1}</span>
                  <p class="remark-text">${r}</p>
                </div>
              `).join('') : `
                <div class="remark-item">
                  <span class="remark-bullet" aria-hidden="true">★</span>
                  <p class="remark-text">Excellent profile! Maintain current performance and focus on interview preparation.</p>
                </div>
              `}
            </div>

            <!-- Footer -->
            <div class="result-footer">
              <p class="result-timestamp">
                Generated · ${timestamp} · Model v1.0
              </p>
              <div style="display:flex;gap:var(--space-3);">
                <button class="btn btn-outline" data-view="history">View in History →</button>
                <button class="btn btn-primary" data-view="predict">New Evaluation →</button>
              </div>
            </div>

          </div>
        </div>
      </div>
    </div>
  `;

  // Animate breakdown bars
  setTimeout(() => {
    main.querySelectorAll('.breakdown-row .progress-bar-fill[data-width]').forEach(bar => {
      const target = bar.getAttribute('data-width');
      bar.style.width = target + '%';
    });
  }, 300);

  // Nav
  main.querySelectorAll('[data-view]').forEach(btn => {
    btn.addEventListener('click', () => Router.navigate(btn.dataset.view));
  });
}

/* ============================================================
   HISTORY PAGE (Prediction Ledger)
   ============================================================ */
function renderHistoryPage() {
  if (!HV.currentUser) { Router.navigate('auth'); return; }

  const history = HV.history;
  const main = document.getElementById('app-main');

  main.innerHTML = `
    <div class="history-page">
      <div class="container">
        <div class="history-header">
          <div>
            <p class="eyebrow">Your Records</p>
            <h2>Prediction Ledger</h2>
            <p style="color:var(--color-navy-mid);font-size:var(--text-sm);margin-top:var(--space-1);">
              Full history of your placement evaluations — newest first.
            </p>
          </div>
          <div style="display:flex;gap:var(--space-3);">
            <button class="btn btn-primary" data-view="predict">New Prediction →</button>
            ${history.length ? `<button class="btn btn-outline" id="clear-history-btn">Clear History</button>` : ''}
          </div>
        </div>

        <div class="history-card reveal">
          <div class="history-card-header">
            <h4>Evaluation History</h4>
            <span class="record-count">${history.length} Record${history.length !== 1 ? 's' : ''}</span>
          </div>

          ${history.length ? `
            <div class="table-wrap">
              <table aria-label="Prediction history table">
                <thead>
                  <tr>
                    <th scope="col">Date</th>
                    <th scope="col">Branch</th>
                    <th scope="col">CGPA</th>
                    <th scope="col">Confidence</th>
                    <th scope="col">Predicted Class</th>
                    <th scope="col">Top Suggestion</th>
                  </tr>
                </thead>
                <tbody>
                  ${history.map((rec, i) => `
                    <tr>
                      <td style="font-family:var(--font-mono);font-size:var(--text-xs);">
                        ${new Date(rec.date).toLocaleDateString('en-IN', { day:'2-digit', month:'short', year:'numeric' })}
                      </td>
                      <td style="font-family:var(--font-mono);font-size:var(--text-xs);">${rec.branch || '—'}</td>
                      <td style="font-weight:600;">${rec.cgpa}</td>
                      <td>
                        <div style="display:flex;align-items:center;gap:var(--space-2);">
                          <div class="progress-bar-wrap" style="width:60px;flex-shrink:0;">
                            <div class="progress-bar-fill ${rec.placed ? 'green' : 'red'}"
                                 style="width:${rec.confidence}%;">
                            </div>
                          </div>
                          <span style="font-family:var(--font-mono);font-size:var(--text-xs);">${rec.confidence}%</span>
                        </div>
                      </td>
                      <td>
                        <span class="pill ${rec.placed ? 'pill-green' : 'pill-red'}">
                          ${rec.placed ? 'Placed' : 'Not Placed'}
                        </span>
                      </td>
                      <td style="font-size:var(--text-xs);color:var(--color-navy-mid);max-width:250px;">
                        ${rec.topSuggestion || '—'}
                      </td>
                    </tr>
                  `).join('')}
                </tbody>
              </table>
            </div>
          ` : `
            <div class="empty-state">
              <div class="empty-state-icon">📋</div>
              <h4>No predictions yet</h4>
              <p>Your evaluation history will appear here after you submit your first form.</p>
              <button class="btn btn-primary" style="margin-top:var(--space-4);" data-view="predict">
                Start First Evaluation →
              </button>
            </div>
          `}
        </div>
      </div>
    </div>
  `;

  main.querySelectorAll('[data-view]').forEach(btn => {
    btn.addEventListener('click', () => Router.navigate(btn.dataset.view));
  });

  const clearBtn = main.querySelector('#clear-history-btn');
  if (clearBtn) {
    clearBtn.addEventListener('click', () => {
      if (confirm('Clear all prediction history? This cannot be undone.')) {
        HV.history = [];
        HV.lastResult = null;
        saveSession();
        showToast('History cleared.', 'info');
        renderHistoryPage();
      }
    });
  }
}
